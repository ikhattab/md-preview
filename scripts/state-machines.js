/**
 * Writes docs/state-machines.md from the definitions in lib/machines/, so the docs can't drift
 * from the code. With --check, fails instead when the file is out of date (`npm run check`).
 */

import { readdirSync, readFileSync, writeFileSync } from 'fs';
import { join, resolve } from 'path';
import { pathToFileURL } from 'url';

const MACHINES_DIR = 'lib/machines';
const OUTPUT = 'docs/state-machines.md';

function isDefinition(value) {
  return value && typeof value.id === 'string' && value.states && value.initial;
}

async function loadDefinitions() {
  const found = [];
  for (const file of readdirSync(MACHINES_DIR).sort()) {
    if (!file.endsWith('.js')) continue;
    const path = join(MACHINES_DIR, file);
    const module = await import(pathToFileURL(resolve(path)).href);
    for (const value of Object.values(module)) {
      if (isDefinition(value)) found.push({ path, definition: value });
    }
  }
  return found.sort((a, b) => a.definition.id.localeCompare(b.definition.id));
}

function transitionsOf(node) {
  return Object.entries(node.on ?? {}).flatMap(([type, value]) =>
    (Array.isArray(value) ? value : [value]).map((t) => ({ type, ...t }))
  );
}

function guardLabel(when) {
  if (!when) return '';
  return when.name && when.name !== 'when' ? ` [${when.name}]` : ' [guarded]';
}

function renderMachine({ path, definition }) {
  const { id, description, element, initial, context = {}, states } = definition;
  const lines = [`## ${id}`, '', description, ''];
  lines.push(`- Defined in [\`${path}\`](../${path})`);
  if (element) lines.push(`- State shown on \`${element}\``);
  const contextKeys = Object.keys(context);
  if (contextKeys.length > 0) {
    lines.push(`- Context: ${contextKeys.map((key) => `\`${key}\``).join(', ')}`);
  }
  lines.push('', '```mermaid', 'stateDiagram-v2', `  [*] --> ${initial}`);
  for (const [name, node] of Object.entries(states)) {
    for (const { type, to, when } of transitionsOf(node)) {
      lines.push(`  ${name} --> ${to ?? name}: ${type}${guardLabel(when)}`);
    }
  }
  lines.push('```', '');
  return lines.join('\n');
}

const definitions = await loadDefinitions();
const markdown = [
  '# State machines',
  '',
  '<!-- Generated by `npm run docs:machines` from lib/machines/. Edit the definitions, not this file. -->',
  '',
  'Every piece of app state that changes over time runs as a finite state machine built with',
  '[`lib/machine.js`](../lib/machine.js). Each definition in `lib/machines/` is pure data: its',
  'states, the events each one accepts, and where each event leads. A state ignores any event',
  "it doesn't list. The module that runs a machine performs its side effects in a listener and",
  'writes the current state to a `data-state` attribute, which tests and devtools can read. In',
  'development, `window.__machines` holds every running machine.',
  '',
  'Arrows show `EVENT [guard]`. An arrow back to the same state changes only the context.',
  '',
  ...definitions.map(renderMachine),
].join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    // Missing counts as out of date.
  }
  if (current !== markdown) {
    console.error(`${OUTPUT} is out of date. Run \`npm run docs:machines\` and commit the result.`);
    process.exit(1);
  }
} else {
  writeFileSync(OUTPUT, markdown);
}
